/**
 * Which shelf of the picker an emoji sits on. Unicode's own top-level ordering, minus Flags.
 *
 * Declaration order is load-bearing in the same way [CoinGroup]'s is: `buildEmojiList` opens a
 * header only on a change of group, so the catalog has to stay in unbroken runs of these.
 */
enum class EmojiGroup(@param:StringRes val label: Int) {
  FACES(R.string.settings_item_emoji_group_faces),
  GESTURES(R.string.settings_item_emoji_group_gestures),
  ANIMALS(R.string.settings_item_emoji_group_animals),
  FOOD(R.string.settings_item_emoji_group_food),
