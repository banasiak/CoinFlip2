  OBJECTS(R.string.settings_item_emoji_group_objects),
  SYMBOLS(R.string.settings_item_emoji_group_symbols)
}

/**
 * One emoji the picker offers.
 *
 * [glyph] is exactly one code point -- no variation selector, no zero-width joiner, no skin-tone
 * modifier, no regional-indicator pair. `EmojiCatalogTests` asserts it, and it is not cosmetic:
 * `Paint.hasGlyph` is only dependable for single code points, and a sequence a device cannot compose
 * lands on the coin as two glyphs side by side.
 *
 * [keywords] is a lowercase, space-separated, **untranslated** search bag, for the same reason
 * `CoinType.coinName` is a plain string: it was never translated, and holding it in Kotlin says so
 * outright where a `string-array` would leave every locale a permanent hole. Nobody is left without
 * a way to find one -- the grid, the group headers and the jump bar are language-free, and the
 * picker matches a pasted glyph too, so the system keyboard's own localized search reaches anything
 * the device can draw.
 */
data class Emoji(val glyph: String, val keywords: String, val group: EmojiGroup)

